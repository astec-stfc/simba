class madxLattice(frameworkLattice):
    """
    Class for defining the MAD-X lattice object, used for converting the
    elements defined in the :class:`~simba.Framework_objects.frameworkLattice`
    into MAD-X ``SEQUENCE`` definitions and for tracking through them with
    `cpymad <https://hibtc.github.io/cpymad/>`_.

    The lattice is split into segments at each RF cavity so that the MAD-X
    reference momentum (to which magnet strengths and canonical track
    coordinates are normalised) can follow the acceleration of the beam; the
    particle coordinates are transformed between the segment-local reference
    frames via the generic :class:`~simba.Modules.Beams.beam` object.

    If :attr:`~single_particle` is False (the default), the full particle
    distribution is tracked and beam distributions are written at each
    diagnostic (`Screen`, `Marker` and `BPM`) in the lattice. If True,
    standard (single-particle) MAD-X tracking is performed for the beam
    centroid and a set of probe trajectories, and only the output beam at the
    end of the line is generated, based on a transformation (centroid offset
    plus finite-difference linear map) of the initial distribution.
    """

    code: str = "madx"
    """String indicating the lattice object type"""

    trackBeam: bool = True
    """Flag to indicate whether to track the beam"""

    single_particle: bool = False
    """If True, perform standard (single particle) MAD-X tracking and only
    generate the output beam at the end of the line based on a transformation
    of the initial distribution. If False (default), track the full particle
    distribution and output beam files at all diagnostics."""

    particle_definition: str = None
    """Initial particle distribution as a string"""

    madxglobal: Dict = {}
    """Global settings for MAD-X, read in from
    `settings["global"]["MADXsettings"]` and `madx_defaults.yaml`"""

    nslice_quadrupole: int = 4
    """Number of MAKETHIN slices for quadrupoles"""

    nslice_sbend: int = 8
    """Number of MAKETHIN slices for bending magnets"""

    cavity_model: str = "rsmatrix"
    """Transverse model for accelerating (RF) cavities:

    - ``rsmatrix`` (default): the transverse motion through the structure is
      described by a first-order MAD-X ``MATRIX`` element containing the
      Rosenzweig-Serafini accelerating-structure matrix (as also used by
      Ocelot), which accounts for adiabatic damping and ponderomotive (RF)
      focusing; the energy gain and RF curvature are applied by a thin
      ``RFCAVITY`` kick. In the fixed-reference-momentum canonical
      coordinates of a segment this matrix is exactly symplectic.

    - ``sliced``: the cavity is subdivided into :attr:`~nslice_rfcavity` thin
      RF kicks with exact drifts in between (adiabatic damping only).

    - ``thin``: a single thin RF kick at the centre of the structure (the
      plain MAD-X MAKETHIN treatment)."""

    nslice_rfcavity: int = 10
    """Number of longitudinal slices for RF cavities when
    :attr:`~cavity_model` is ``sliced``. Since the MAD-X thin-lens
    tracking module applies RF cavities as single kicks (MAKETHIN does not
    subdivide them), cavities are subdivided at the sequence level into
    `nslice_rfcavity` sub-cavities, each carrying 1/n of the voltage. The
    (exact) drifts between the resulting thin kicks then reproduce the
    adiabatic damping of the transverse coordinates along an accelerating
    structure."""

    nslice_default: int = 1
    """Default number of MAKETHIN slices for all other thick elements"""

    makethin_style: str = "teapot"
    """Slicing style for the MAD-X MAKETHIN command"""

    makedipedge: bool = True
    """Flag to control the generation of DIPEDGE elements in MAKETHIN"""

    maxaper: List = [100.0, 100.0, 100.0, 100.0, 1000.0, 1000.0]
    """Upper limits for the particle coordinates [x, px, y, py, t, pt] used by
    the MAD-X RUN command; kept deliberately large so that particles are not
    artificially collimated (consistent with the other tracking codes)"""

    write_model_twiss: bool = True
    """If True, compute the MAD-X model Twiss parameters (via the TWISS
    command) for each segment and include them in the Twiss output file"""

    fd_delta: float = 1e-6
    """Finite-difference step used to build the linear map in
    ``single_particle`` mode"""

    segments: List = []
    """List of lattice segments; each segment is a list of element names and
    is tracked with a constant MAD-X reference momentum"""

    seqstrings: List = []
    """MAD-X SEQUENCE definitions for each segment"""

    pin: Any = None
    """Initial particle distribution as a :class:`~simba.Modules.Beams.beam`"""

    pout: Any = None
    """Final particle distribution as a :class:`~simba.Modules.Beams.beam`"""

    tws: Dict = {}
    """Dictionary of arrays containing the collected Twiss/beam-statistics
    data along the lattice"""

    beam_data: Dict = {}
    """Data containing beam statistics at each observation point"""

    model_twiss: Dict = {}
    """MAD-X model Twiss parameters at each element, keyed by element name"""

    segment_p0c: Dict = {}
    """MAD-X reference momentum [eV/c] of the segment each element belongs to,
    keyed by element name. Used to convert the canonical model Twiss functions
    back to trace space (see :func:`~postProcess`)"""

    output_beams: Dict = {}
    """Beam distributions at each observation point, keyed by element name"""

    ref_s: float = None
    """Reference s position"""

    ref_idx: int = None
    """Reference particle index"""

    logfile: Any = None
    """File handle for the MAD-X log file"""

    def model_post_init(self, __context):
        super().model_post_init(__context)
        self.madxglobal = deepcopy(madxglobal)
        if "MADXsettings" in list(self.settings["global"].keys()):
            for k, v in self.settings["global"]["MADXsettings"].items():
                self.madxglobal.update({k: v})
        # settable configuration fields, from global settings or the lattice
        # file block
        for f in list(madxglobal.keys()) + ["trackBeam"]:
            if f in self.madxglobal:
                setattr(self, f, self.madxglobal[f])
            if f in self.file_block:
                setattr(self, f, self.file_block[f])
        if (
            "input" in self.file_block
            and "particle_definition" in self.file_block["input"]
        ):
            if (
                self.file_block["input"]["particle_definition"]
                == "initial_distribution"
            ):
                self.particle_definition = "laser"
            else:
                self.particle_definition = self.file_block["input"][
                    "particle_definition"
                ]
        else:
            self.particle_definition = self.start
        self.segments = []
        self.seqstrings = []
        self.beam_data = {}
        self.model_twiss = {}
        self.segment_p0c = {}
        self.output_beams = {}
        self.tws = {}

    # ------------------------------------------------------------------
    # Lattice generation
    # ------------------------------------------------------------------
    @property
    def particle_rest_energy_eV(self) -> float:
        """Rest energy of the tracked particles in eV"""
        try:
            return float(
                np.mean(self.global_parameters["beam"].particle_rest_energy_eV.val)
            )
        except Exception:
            return constants.m_e * speed_of_light**2 / elementary_charge

    def segmentElements(self) -> List:
        """
        Split the lattice (including explicit drifts) into segments, breaking
        after each RF cavity. Within each segment the beam energy -- and
        therefore the MAD-X reference momentum -- is constant, which allows
        normalised magnet strengths to be interpreted at the local design
        momentum, in the same way as for the other supported tracking codes.

        Returns
        -------
        List
            A list of segments, each a list of element names (in order).
        """
        elements_with_drifts = self.section.createDrifts()
        self._elements_with_drifts = elements_with_drifts
        self._elem_dict = translate_elements(
            list(elements_with_drifts.values()),
            master_lattice=self.global_parameters["master_lattice"],
            directory=self.global_parameters["master_subdir"],
        )
        self._sval_in = self.section.get_s_values(as_dict=True, at_entrance=True)
        self._sval_out = self.section.get_s_values(as_dict=True, at_entrance=False)
        segments = []
        current = []
        for name, elem in self._elem_dict.items():
            current.append(name)
            # segment boundaries at accelerating cavities (but not
            # transverse deflecting cavities, which do not change the
            # reference momentum)
            if elem.hardware_type.lower() == "rfcavity":
                segments.append(current)
                current = []
        if len(current) > 0:
            segments.append(current)
        self.segments = segments
        return segments

    def writeElements(self) -> str:
        """
        Create the MAD-X ``SEQUENCE`` definitions for all segments of the
        lattice, using ``refer=centre`` positioning (as required by the MAD-X
        ``MAKETHIN`` command) and set :attr:`~seqstrings`.

        Returns
        -------
        str
            The full lattice represented as a string compatible with MAD-X
        """
        self.segmentElements()
        self.seqstrings = []
        self._design_energy = self.initial_energy()
        fulltext = madx_functional_definitions(self.section.functional_definitions)
        for iseg, segnames in enumerate(self.segments):
            seqname = self.segment_name(iseg)
            seg_s0 = self._sval_in[segnames[0]]
            seg_s1 = self._sval_out[segnames[-1]]
            seg_len = seg_s1 - seg_s0
            lines = [f"{seqname}: sequence, refer=centre, l = {seg_len};"]
            for name in segnames:
                d = self._elem_dict[name]
                if getattr(d, "subelement", False):
                    at = (
                        d.physical.start.z
                        - self.startObject.physical.start.z
                        - seg_s0
                        + d.physical.length / 2.0
                    )
                else:
                    at = self._sval_in[name] - seg_s0 + d.physical.length / 2.0
                estr = d.to_madx(at=at).strip()
                if d.hardware_type.lower() == "rfcavity":
                    if self.cavity_model.lower() == "rsmatrix":
                        estr, self._design_energy = self.rs_matrix_cavity(
                            estr, d.physical.length, at, self._design_energy
                        )
                    elif (
                        self.cavity_model.lower() == "sliced"
                        and self.nslice_rfcavity > 1
                    ):
                        estr = self.slice_cavity(estr, d.physical.length, at)
                lines.append(estr)
            lines.append("endsequence;")
            seqstr = "\n".join(lines)
            self.seqstrings.append(seqstr)
            fulltext += f"\n! ------------------ segment {iseg} ------------------\n"
            fulltext += seqstr + "\n"
        return fulltext

    def segment_name(self, iseg: int) -> str:
        """MAD-X compatible name for lattice segment `iseg`"""
        return f"{sanitize_string(self.objectname)}_seg_{iseg}"

    def initial_energy(self) -> float:
        """
        Total energy [eV] of the input beam (used to accumulate the design
        energy along the segments when building the cavity matrices). Returns
        0 if no beam has been loaded yet.
        """
        for bm in [self.pin, self.global_parameters.get("beam", None)]:
            try:
                if bm is not None and len(bm.x.val) > 0:
                    return float(np.mean(bm.energy.val))
            except Exception:
                continue
        return 0.0

    def parse_madx_element(self, estr: str) -> tuple:
        """
        Parse a MAD-X element definition string into its name, type and
        attribute dictionary.

        Parameters
        ----------
        estr: str
            MAD-X element definition, e.g. ``name: rfcavity, volt = 1, ...;``

        Returns
        -------
        tuple
            (name, type, attributes)
        """
        head, _, body = estr.partition(":")
        elemname = head.strip()
        body = body.strip().rstrip(";")
        parts = [p.strip() for p in body.split(",")]
        etype = parts[0].strip().lower()
        attrs = {}
        for p in parts[1:]:
            mm = re.match(r"^(\w+)\s*=\s*(.+)$", p)
            if mm:
                attrs[mm.group(1).lower()] = mm.group(2).strip()
        return elemname, etype, attrs

    def rs_matrix_cavity(
        self,
        cavstring: str,
        length: float,
        at: float,
        energy: float,
    ) -> tuple:
        """
        Convert an RF cavity definition into a first-order MAD-X ``MATRIX``
        element containing the Rosenzweig-Serafini accelerating-structure
        matrix (the same transverse model used by Ocelot, with eta = 1),
        followed by a thin ``RFCAVITY`` applying the energy gain and RF
        curvature. In the fixed-reference-momentum canonical coordinates
        (px = Px/P0) of a lattice segment the resulting 4x4 transverse matrix
        is exactly symplectic, so it can be used directly by the MAD-X
        thin-lens tracking and Twiss modules.

        Parameters
        ----------
        cavstring: str
            The full MAD-X element definition for the cavity
        length: float
            Physical length of the cavity [m]
        at: float
            Position of the cavity centre within the segment [m]
        energy: float
            Total beam (design) energy at the entrance of the cavity [eV]

        Returns
        -------
        tuple
            (MAD-X definitions string, energy at the exit of the cavity [eV])
        """
        m0 = self.particle_rest_energy_eV
        if ":=" in cavstring or energy <= m0:
            if energy <= m0:
                warn(
                    "MADX: beam energy unknown when writing the lattice -- "
                    "using a thin-kick cavity model. Call preProcess() "
                    "before write() to enable the rsmatrix cavity model."
                )
            return cavstring, energy
        elemname, etype, attrs = self.parse_madx_element(cavstring)
        if etype != "rfcavity":
            return cavstring, energy
        try:
            volt = float(attrs.get("volt", 0.0)) * 1e6  # MV -> eV
            lag = float(attrs.get("lag", 0.0))
            L = float(attrs.get("l", length))
        except ValueError:
            return cavstring, energy
        de = volt * np.sin(2 * np.pi * lag)
        if L <= 0 or abs(de) < 1e-9 * max(energy, 1.0):
            return cavstring, energy + de
        # Rosenzweig-Serafini matrix (pure pi-mode standing wave, eta = 1),
        # as implemented in the Ocelot CavityAtom first-order map
        cos_phi = np.sin(2 * np.pi * lag)  # = cos(phase) off-crest convention
        Ei = energy / m0
        Ef = (energy + de) / m0
        Ep = (Ef - Ei) / L
        alpha = np.sqrt(1.0 / 8.0) / cos_phi * np.log(Ef / Ei)
        sin_a, cos_a = np.sin(alpha), np.cos(alpha)
        r11 = cos_a - np.sqrt(2.0) * cos_phi * sin_a
        r12 = np.sqrt(8.0) * Ei / Ep * cos_phi * sin_a if abs(Ep) > 1e-10 else L
        r21 = -Ep / Ef * (cos_phi / np.sqrt(2.0) + np.sqrt(1.0 / 8.0) / cos_phi) * sin_a
        r22 = Ei / Ef * (cos_a + np.sqrt(2.0) * cos_phi * sin_a)
        # convert from trace-space (x, x') to the segment's canonical
        # coordinates (x, px = Px/P0) with P0 = P(entrance): the resulting
        # matrix has unit determinant
        Pi = np.sqrt(Ei**2 - 1.0)
        Pf = np.sqrt(Ef**2 - 1.0)
        m11, m12 = r11, r12
        m21, m22 = r21 * Pf / Pi, r22 * Pf / Pi
        matrixstr = (
            f"{elemname}_RSM: matrix, l = {L}, "
            f"rm11 = {m11}, rm12 = {m12}, rm21 = {m21}, rm22 = {m22}, "
            f"rm33 = {m11}, rm34 = {m12}, rm43 = {m21}, rm44 = {m22}, "
            f"at = {at};"
        )
        others = {k: v for k, v in attrs.items() if k not in ("l", "at")}
        cavstr = (
            f"{elemname}: rfcavity, l = 0, "
            + ", ".join([f"{k} = {v}" for k, v in others.items()])
            + f", at = {at + L / 2.0};"
        )
        return matrixstr + "\n" + cavstr, energy + de

    def slice_cavity(self, cavstring: str, length: float, at: float) -> str:
        """
        Subdivide an RF cavity definition into :attr:`~nslice_rfcavity`
        sub-cavities, each with 1/n of the voltage (and length), placed
        uniformly along the body of the structure. The MAD-X thin-lens
        tracking module applies each sub-cavity as a thin RF kick, with exact
        drifts in between, which reproduces the adiabatic damping of the
        transverse coordinates through the accelerating structure (a single
        lumped kick would let the beam expand at the injection energy over
        half the structure length before feeling any acceleration).

        The last slice keeps the original element name, so that observation
        points and Twiss-table lookups remain valid.

        Parameters
        ----------
        cavstring: str
            The full MAD-X element definition for the cavity
        length: float
            Physical length of the cavity [m]
        at: float
            Position of the cavity centre within the segment [m]

        Returns
        -------
        str
            The MAD-X definitions of the sub-cavities (or the original
            definition if it cannot safely be sliced)
        """
        n = int(self.nslice_rfcavity)
        if n <= 1 or length <= 0:
            return cavstring
        # deferred (":=") expressions cannot be rescaled safely
        if ":=" in cavstring:
            return cavstring
        elemname, etype, attrs = self.parse_madx_element(cavstring)
        if etype != "rfcavity":
            return cavstring
        try:
            volt = float(attrs.get("volt", 0.0))
            L = float(attrs.get("l", length))
        except ValueError:
            return cavstring
        others = {
            k: v for k, v in attrs.items() if k not in ("volt", "l", "at")
        }
        lines = []
        for k in range(n):
            slname = elemname if k == n - 1 else f"{elemname}_SL{k + 1}"
            slat = at - L / 2.0 + (k + 0.5) * L / n
            attrstr = ", ".join(
                [f"volt = {volt / n}", f"l = {L / n}"]
                + [f"{k2} = {v2}" for k2, v2 in others.items()]
                + [f"at = {slat}"]
            )
            lines.append(f"{slname}: rfcavity, {attrstr};")
        return "\n".join(lines)

    def write(self) -> None:
        """
        Create the lattice representation via
        :func:`~simba.Codes.MADX.MADX.madxLattice.writeElements` and save it
        as a MAD-X input file to `master_subdir`.
        """
        fulltext = self.writeElements()
        latticefile = (
            self.global_parameters["master_subdir"] + "/" + self.objectname + ".madx"
        )
        with open(latticefile, "w") as f:
            f.write(fulltext)
        self.files.append(latticefile)

    # ------------------------------------------------------------------
    # Pre-processing
    # ------------------------------------------------------------------
    def preProcess(self) -> None:
        """
        Get the initial particle distribution defined in
        `file_block['input']['prefix']` if it exists.
        """
        super().preProcess()
        prefix = self.get_prefix()
        prefix = prefix if self.trackBeam else prefix + self.particle_definition
        self.read_input_file(prefix, self.particle_definition)
        if self.initial_twiss["horizontal"]["beta"]:
            self.global_parameters["beam"].beam.rematchXPlane(
                **self.initial_twiss["horizontal"]
            )
        if self.initial_twiss["vertical"]["beta"]:
            self.global_parameters["beam"].beam.rematchYPlane(
                **self.initial_twiss["vertical"]
            )
        self.ref_s = self.global_parameters["beam"].s
        self.ref_idx = self.global_parameters["beam"].reference_particle_index
        self.pin = deepcopy(self.global_parameters["beam"])

    # ------------------------------------------------------------------
    # MAD-X interaction
    # ------------------------------------------------------------------
    def start_madx(self) -> Any:
        """
        Start a `cpymad` MAD-X interpreter, logging its output to
        `<lattice>.log` in `master_subdir`.

        Returns
        -------
        cpymad.madx.Madx
            The MAD-X instance
        """
        from cpymad.madx import Madx

        self.logfile = open(
            os.path.join(
                self.global_parameters["master_subdir"], self.objectname + ".log"
            ),
            "w",
        )
        madx = Madx(
            stdout=self.logfile,
            cwd=self.global_parameters["master_subdir"],
        )
        madx.option(echo=False, warn=True, info=False, twiss_print=False)
        if self.section.functional_definitions:
            madx.input(
                madx_functional_definitions(self.section.functional_definitions)
            )
        return madx

    def madx_beam_command(self, madx: Any, p0c: float, seqname: str) -> None:
        """
        Issue the MAD-X ``BEAM`` command for a segment, with the reference
        momentum `p0c` (in eV/c) and the mass/charge of the tracked species.
        """
        m0 = self.particle_rest_energy_eV
        chargesign = int(np.sign(np.mean(self.global_parameters["beam"].Q.val)) or -1)
        species = getattr(self.global_parameters["beam"], "species", "electron")
        if species in madx_particle_names:
            madx.input(
                f"beam, particle={madx_particle_names[species]}, pc={p0c / 1e9}, "
                f"sequence={seqname};"
            )
        else:
            madx.input(
                f"beam, mass={m0 / 1e9}, charge={chargesign}, pc={p0c / 1e9}, "
                f"sequence={seqname};"
            )

    def makethin(self, madx: Any, seqname: str) -> None:
        """
        Slice the (thick) segment sequence into thin lenses with the MAD-X
        ``MAKETHIN`` command (required by the thin-lens tracking module), and
        re-``USE`` the sequence.
        """
        madedge = "true" if self.makedipedge else "false"
        madx.input(
            f"""
            select, flag=makethin, clear;
            select, flag=makethin, class=matrix, slice=0;
            select, flag=makethin, class=quadrupole, slice={self.nslice_quadrupole};
            select, flag=makethin, class=sbend, slice={self.nslice_sbend};
            select, flag=makethin, class=rbend, slice={self.nslice_sbend};
            select, flag=makethin, class=rfcavity, slice=1;
            makethin, sequence={seqname}, style={self.makethin_style}, makedipedge={madedge};
            use, sequence={seqname};
            """
        )

    def observation_points(self, segnames: List) -> List:
        """
        The observation points for a segment: all zero-length diagnostics
        (`Screen`, `Marker` and `BPM` types) within the segment.

        Parameters
        ----------
        segnames: List
            Names of the elements in the segment

        Returns
        -------
        List
            (name, s position within segment) tuples
        """
        diag_names = [e.name for e in self.screens_and_markers_and_bpms]
        seg_s0 = self._sval_in[segnames[0]]
        obs = []
        for name in segnames:
            if name in diag_names and self._elem_dict[name].physical.length == 0:
                obs.append((name, self._sval_in[name] - seg_s0))
        return obs

    def run_track(
        self,
        madx: Any,
        coords: Dict,
        observe: List,
        numbers: np.ndarray = None,
    ) -> Dict:
        """
        Run the MAD-X thin-lens tracking module (``TRACK``/``START``/
        ``OBSERVE``/``RUN``/``ENDTRACK``) for one segment and return the
        contents of the ``trackone`` table.

        Parameters
        ----------
        madx: cpymad.madx.Madx
            The MAD-X instance
        coords: Dict
            The canonical starting coordinates
        observe: List
            (name, s) tuples at which to observe the beam
        numbers: np.ndarray, optional
            Particle numbers to assign (defaults to 1..N)

        Returns
        -------
        Dict
            Dictionary of arrays from the MAD-X `trackone` table
        """
        npart = len(coords["x"])
        madx.input("track, onepass, onetable;")
        startlines = []
        for i in range(npart):
            startlines.append(
                "start, x={:.15g}, px={:.15g}, y={:.15g}, py={:.15g}, "
                "t={:.15g}, pt={:.15g};".format(
                    coords["x"][i],
                    coords["px"][i],
                    coords["y"][i],
                    coords["py"][i],
                    coords["t"][i],
                    coords["pt"][i],
                )
            )
        # chunk the input to avoid very large single commands
        for i in range(0, len(startlines), 4096):
            madx.input("\n".join(startlines[i: i + 4096]))
        for name, sobs in observe:
            madx.input(f"observe, place={sanitize_string(name)};")
        maxaper = "{" + ",".join([str(v) for v in self.maxaper]) + "}"
        madx.input(f"run, turns=1, maxaper={maxaper};")
        madx.input("endtrack;")
        tbl = madx.table.trackone
        return {
            k: np.array(tbl[k])
            for k in ["number", "turn", "x", "px", "y", "py", "t", "pt", "s"]
        }

    def extract_observation(self, trackdata: Dict, s_target: float) -> Dict:
        """
        Extract the particle coordinates recorded at a given s position from
        the ``trackone`` table data, de-duplicated and ordered by particle
        number.

        Parameters
        ----------
        trackdata: Dict
            The `trackone` table data
        s_target: float
            The s position of the observation point within the segment

        Returns
        -------
        Dict
            Dictionary of coordinate arrays (including the surviving particle
            `number` array)
        """
        mask = (np.abs(trackdata["s"] - s_target) < 1e-8) & (trackdata["turn"] >= 1)
        if not np.any(mask) and abs(s_target) < 1e-8:
            # observation point at the very start of the segment -- use the
            # starting coordinates (turn 0)
            mask = (np.abs(trackdata["s"] - s_target) < 1e-8) & (
                trackdata["turn"] == 0
            )
        out = {k: trackdata[k][mask] for k in trackdata}
        order = np.argsort(out["number"], kind="stable")
        out = {k: out[k][order] for k in out}
        _, uidx = np.unique(out["number"], return_index=True)
        return {k: out[k][uidx] for k in out}

    def model_twiss_segment(
        self,
        madx: Any,
        seqname: str,
        init: Dict,
    ) -> Dict:
        """
        Compute the MAD-X model Twiss parameters for a segment with initial
        conditions `init`, and return the initial conditions for the next
        segment together with the Twiss data at each element.

        Parameters
        ----------
        madx: cpymad.madx.Madx
            The MAD-X instance
        seqname: str
            The name of the segment sequence
        init: Dict
            Initial Twiss conditions (betx, alfx, bety, alfy, dx, dpx, dy,
            dpy, mux, muy)

        Returns
        -------
        Dict
            Initial conditions for the next segment; the element-by-element
            data are accumulated into :attr:`~model_twiss`
        """
        try:
            madx.input(
                f"twiss, sequence={seqname}, betx={init['betx']}, alfx={init['alfx']}, "
                f"bety={init['bety']}, alfy={init['alfy']}, dx={init['dx']}, "
                f"dpx={init['dpx']}, dy={init['dy']}, dpy={init['dpy']};"
            )
            tw = madx.table.twiss
            names = [str(n).split(":")[0].lower() for n in tw["name"]]
            if len(names) == 0 or not names[0].startswith(seqname.lower()):
                raise ValueError(f"twiss table does not match segment {seqname}")
            data = {
                k: np.array(tw[k])
                for k in ["s", "betx", "alfx", "bety", "alfy", "dx", "dpx", "dy", "dpy", "mux", "muy"]
            }
        except Exception as e:
            warn(f"MAD-X twiss failed for {seqname}: {e}")
            return init
        for i, name in enumerate(names):
            self.model_twiss[name] = {
                "betx": data["betx"][i],
                "alfx": data["alfx"][i],
                "bety": data["bety"][i],
                "alfy": data["alfy"][i],
                "dx": data["dx"][i],
                "dpx": data["dpx"][i],
                "dy": data["dy"][i],
                "dpy": data["dpy"][i],
                "mux": data["mux"][i] + init["mux"],
                "muy": data["muy"][i] + init["muy"],
            }
        return {
            "betx": data["betx"][-1],
            "alfx": data["alfx"][-1],
            "bety": data["bety"][-1],
            "alfy": data["alfy"][-1],
            "dx": data["dx"][-1],
            "dpx": data["dpx"][-1],
            "dy": data["dy"][-1],
            "dpy": data["dpy"][-1],
            "mux": data["mux"][-1] + init["mux"],
            "muy": data["muy"][-1] + init["muy"],
        }


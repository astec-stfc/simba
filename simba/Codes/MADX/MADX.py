"""
SIMBA MAD-X Module

Various objects and functions to handle MAD-X lattices and tracking. The
interaction with MAD-X is handled through the `cpymad`_ library, which embeds
the MAD-X interpreter in the Python process; see the `MAD-X manual`_ for
details of the underlying commands.

    .. _cpymad: https://hibtc.github.io/cpymad/
    .. _MAD-X manual: https://madx.web.cern.ch/webguide/manual.html

The lattice (including explicit drifts) is converted into one or more MAD-X
``SEQUENCE`` blocks via the LAURA
:class:`~laura.translator.converters.section.SectionLatticeTranslator`
machinery. Since MAD-X reference momentum is fixed for a given ``BEAM``
statement (magnet strengths are normalised to it, and tracking coordinates are
canonical w.r.t. it), the lattice is split into segments at each accelerating
(RF) cavity. Each segment is tracked with the local reference momentum taken
from the tracked bunch itself, and the particle coordinates are re-referenced
between segments -- mirroring the ``always_change_p0`` behaviour used for
ELEGANT and the internal energy bookkeeping of Ocelot, so that the beam
evolution can be interpreted in the same way as for the other tracking codes.

Two tracking modes are available:

- Full-beam tracking (default): every macro-particle in the input
  distribution is tracked with the thin-lens tracking module (``TRACK`` ...
  ``START`` ... ``RUN``), and output beam distributions are written (in
  OpenPMD HDF5 format) at every diagnostic (``Screen``, ``Marker`` and
  ``BPM``) in the lattice, as well as at the end of the line.

- ``single_particle`` mode: only the beam centroid (plus a small set of probe
  trajectories used to build the linear map by finite differences) is tracked
  through each segment with standard MAD-X tracking. The output beam at the
  end of the line is then generated by applying the resulting transformation
  (centroid + linear map) to the initial particle distribution. No
  intermediate diagnostic outputs are produced in this mode.

In both cases a Twiss summary file (``<lattice>_twiss.madx.hdf5``) is written,
containing both the MAD-X model optics (Twiss functions, dispersion, phase
advances) and beam-distribution statistics (momentum, sizes, bunch length,
emittances), which can be loaded through
:func:`simba.Modules.Twiss.load_directory` in the same way as the output of
the other tracking codes.

Classes:
    - :class:`~simba.Codes.MADX.MADX.madxLattice`: The MAD-X lattice object,
      used for converting the elements defined in the
      :class:`~simba.Framework_objects.frameworkLattice` into MAD-X sequences,
      and for tracking through them using `cpymad`.
"""


    # Tracking
    # ------------------------------------------------------------------
    def initial_twiss_conditions(self, bm: rbf.beam) -> Dict:
        """Initial Twiss conditions for the model Twiss, from the beam"""
        try:
            return {
                "betx": float(bm.twiss.beta_x_corrected),
                "alfx": float(bm.twiss.alpha_x_corrected),
                "bety": float(bm.twiss.beta_y_corrected),
                "alfy": float(bm.twiss.alpha_y_corrected),
                "dx": 0.0,
                "dpx": 0.0,
                "dy": 0.0,
                "dpy": 0.0,
                "mux": 0.0,
                "muy": 0.0,
            }
        except Exception:
            return {
                "betx": 1.0,
                "alfx": 0.0,
                "bety": 1.0,
                "alfy": 0.0,
                "dx": 0.0,
                "dpx": 0.0,
                "dy": 0.0,
                "dpy": 0.0,
                "mux": 0.0,
                "muy": 0.0,
            }

    @staticmethod
    def rescale_twiss_init(init: Dict, ratio: float) -> Dict:
        """
        Re-reference a set of Twiss functions from one MAD-X reference
        momentum to another (``ratio`` = p0c_new / p0c_old).

        The MAD-X Twiss functions are defined in the canonical coordinates
        (x, px = Px/P0) of the segment, so they depend on the segment
        reference momentum. Since the beam is accelerated by the cavity at the
        end of each segment, the reference momentum changes at every segment
        boundary and the Twiss functions have to be transformed accordingly.

        Under P0 -> P0' the transverse coordinate x is unchanged while
        px -> px * P0/P0', so the canonical emittance scales as
        eps -> eps * P0/P0'. Hence beta (= sigma_x^2/eps) and the dispersion
        (per unit pt, which rescales the same way) are multiplied by `ratio`,
        while alpha and dpx/dpy are invariant.
        """
        if not np.isfinite(ratio) or ratio <= 0:
            return init
        out = dict(init)
        for key in ("betx", "bety", "dx", "dy"):
            out[key] = init[key] * ratio
        return out

    def store_beam_data(self, name: str, bm: rbf.beam, spos: float, zpos: float) -> None:
        """
        Store the beam statistics at an observation point into
        :attr:`~beam_data`, in a form that can be interpreted in the same way
        as the outputs of the other tracking codes.
        """
        try:
            eta_x = float(bm.twiss.eta_x)
            eta_xp = float(bm.twiss.eta_xp)
            eta_y = float(bm.twiss.eta_y)
            eta_yp = float(bm.twiss.eta_yp)
        except Exception:
            eta_x = eta_xp = eta_y = eta_yp = 0.0
        self.beam_data[name] = {
            "s": spos,
            "z": zpos,
            "t": float(np.mean(bm.t.val)),
            "cp": float(np.mean(bm.cp.val)),
            "sigma_x": float(bm.sigmas.sigma_x),
            "sigma_y": float(bm.sigmas.sigma_y),
            "sigma_xp": float(bm.sigmas.sigma_xp) if hasattr(bm.sigmas, "sigma_xp") else float(np.std(bm.xp.val)),
            "sigma_yp": float(bm.sigmas.sigma_yp) if hasattr(bm.sigmas, "sigma_yp") else float(np.std(bm.yp.val)),
            "sigma_t": float(bm.sigmas.sigma_t),
            "sigma_z": float(bm.sigmas.sigma_z),
            "sigma_cp": float(bm.sigmas.sigma_cp_eV),
            "mean_x": float(np.mean(bm.x.val)),
            "mean_y": float(np.mean(bm.y.val)),
            "ex": float(bm.emittance.ex),
            "ey": float(bm.emittance.ey),
            "enx": float(bm.emittance.enx),
            "eny": float(bm.emittance.eny),
            "ecnx": float(bm.emittance.ecnx),
            "ecny": float(bm.emittance.ecny),
            "beta_x_beam": float(bm.twiss.beta_x_corrected),
            "alpha_x_beam": float(bm.twiss.alpha_x_corrected),
            "beta_y_beam": float(bm.twiss.beta_y_corrected),
            "alpha_y_beam": float(bm.twiss.alpha_y_corrected),
            "eta_x_beam": eta_x,
            "eta_xp_beam": eta_xp,
            "eta_y_beam": eta_y,
            "eta_yp_beam": eta_yp,
        }

    def write_output_beam(self, name: str, bm: rbf.beam) -> None:
        """
        Write a beam distribution to an OpenPMD HDF5 file named after the
        element at which it was observed.
        """
        fname = os.path.join(
            self.global_parameters["master_subdir"], f"{name}.openpmd.hdf5"
        )
        rbf.openpmd.write_openpmd_beam_file(bm, fname)
        self.output_beams[name] = bm

    def run(self) -> None:
        """
        Run MAD-X tracking through all segments via `cpymad`, setting the
        MAD-X reference momentum of each segment to the mean momentum of the
        tracked bunch at its entrance, and re-referencing the canonical
        particle coordinates between segments.

        In full-beam mode (default), every particle in the (sampled) input
        distribution is tracked and the beam is recorded at every diagnostic;
        in :attr:`~single_particle` mode, the beam centroid and 12 probe
        particles are tracked to build the segment maps, which are then
        applied to the initial distribution to generate the output beam at
        the end of the line.
        """
        if len(self.seqstrings) == 0:
            self.writeElements()
        self.beam_data = {}
        self.model_twiss = {}
        self.output_beams = {}
        madx = self.start_madx()
        try:
            self.run_segments(madx)
        finally:
            try:
                madx.exit()
            except Exception:
                pass
            if self.logfile is not None:
                self.logfile.close()
                self.logfile = None

    def run_segments(self, madx: Any) -> None:
        """Track through each lattice segment in turn; see :func:`~run`."""
        sstart_lattice = self.start_s
        current_beam = deepcopy(self.pin)
        if not self.single_particle and self.sample_interval > 1:
            current_beam = self.sample_beam(current_beam, self.sample_interval)
        ref_idx = current_beam.reference_particle_index
        charge_total = abs(np.sum(np.array(current_beam.charge.val)))
        twiss_init = self.initial_twiss_conditions(current_beam)

        # store the beam data at the entrance of the lattice
        self.segment_p0c[self.start] = float(np.mean(current_beam.cp.val))
        self.store_beam_data(
            self.start,
            current_beam,
            self._sval_in[self.segments[0][0]] + sstart_lattice,
            self.startObject.physical.start.z,
        )

        p0c_prev = None
        for iseg, segnames in enumerate(self.segments):
            seqname = self.segment_name(iseg)
            seg_s0 = self._sval_in[segnames[0]]
            seg_s1 = self._sval_out[segnames[-1]]
            seg_len = seg_s1 - seg_s0
            p0c = float(np.mean(current_beam.cp.val))
            # the MAD-X Twiss functions are canonical w.r.t. the segment
            # reference momentum, which changes at every segment boundary
            if p0c_prev is not None and p0c_prev > 0:
                twiss_init = self.rescale_twiss_init(twiss_init, p0c / p0c_prev)
            p0c_prev = p0c
            for nm in segnames:
                self.segment_p0c[nm] = p0c
            if getattr(self, "verbose", False):
                print(
                    f"MADX [{self.objectname}] segment {iseg + 1}/{len(self.segments)}: "
                    f"s = {seg_s0:.3f} -> {seg_s1:.3f} m, p0c = {p0c / 1e6:.3f} MeV/c"
                )
            madx.input(self.seqstrings[iseg])
            self.madx_beam_command(madx, p0c, seqname)
            madx.use(sequence=seqname)
            self.makethin(madx, seqname)

            if self.write_model_twiss:
                twiss_init = self.model_twiss_segment(madx, seqname, twiss_init)

            if self.single_particle:
                current_beam = self.track_segment_single_particle(
                    madx, current_beam, p0c, seg_len, segnames,
                    seg_s0, sstart_lattice,
                )
                if segnames[-1] not in self.beam_data:
                    endelem = self._elements_with_drifts[segnames[-1]]
                    self.store_beam_data(
                        segnames[-1],
                        current_beam,
                        seg_s1 + sstart_lattice,
                        endelem.physical.end.z,
                    )
            else:
                current_beam = self.track_segment_beam(
                    madx,
                    current_beam,
                    p0c,
                    segnames,
                    seg_s0,
                    seg_len,
                    sstart_lattice,
                    charge_total,
                    ref_idx,
                )
                charge_total = abs(np.sum(np.array(current_beam.charge.val)))
                ref_idx = current_beam.reference_particle_index

        self.pout = current_beam
        # store/write the final beam at the end of the line
        endname = self.end
        endelem = self._elements_with_drifts[self.segments[-1][-1]]
        self.segment_p0c.setdefault(endname, p0c_prev)
        self.store_beam_data(
            endname,
            current_beam,
            self._sval_out[self.segments[-1][-1]] + sstart_lattice,
            endelem.physical.end.z,
        )
        self.write_output_beam(endname, current_beam)

    def track_segment_beam(
        self,
        madx: Any,
        current_beam: rbf.beam,
        p0c: float,
        segnames: List,
        seg_s0: float,
        seg_len: float,
        sstart_lattice: float,
        charge_total: float,
        ref_idx: int,
    ) -> rbf.beam:
        """
        Track the full particle distribution through one segment, recording
        (and writing) the beam distributions at each diagnostic within the
        segment; see :func:`~run`.

        Returns
        -------
        :class:`~simba.Modules.Beams.beam`
            The beam at the end of the segment
        """
        npart = len(current_beam.x.val)
        coords = current_beam.beam_to_madx_coords(p0c)
        tbar0 = coords["tbar"]
        observe = self.observation_points(segnames)
        trackdata = self.run_track(madx, coords, observe)
        charge_per_particle = charge_total / npart

        for name, s_local in observe:
            data = self.extract_observation(trackdata, s_local)
            if len(data["x"]) == 0:
                warn(f"MADX: no particles recorded at {name}")
                continue
            elem = self._elements_with_drifts[name]
            bm = self.pin.madx_coords_to_beam(
                data,
                p0c,
                tbar0,
                s_local,
                elem.physical.middle.z,
                elem.physical.middle.z,
                charge_per_particle * len(data["x"]),
                ref_index=self.reference_index(data["number"], ref_idx),
            )
            self.store_beam_data(
                name, bm, seg_s0 + s_local + sstart_lattice, elem.physical.middle.z
            )
            if not name == self.end:
                self.write_output_beam(name, bm)

        # end-of-segment beam (MAD-X automatically observes at the end of the
        # sequence)
        data = self.extract_observation(trackdata, seg_len)
        nlost = npart - len(data["x"])
        if nlost > 0:
            warn(f"MADX: {nlost} particles lost in segment")
        endelem = self._elements_with_drifts[segnames[-1]]
        newref = self.reference_index(data["number"], ref_idx)
        bm = self.pin.madx_coords_to_beam(
            data,
            p0c,
            tbar0,
            seg_len,
            endelem.physical.end.z,
            endelem.physical.end.z,
            charge_per_particle * len(data["x"]),
            ref_index=newref,
        )
        # record beam data at the exit of the segment (i.e. after the
        # accelerating cavity)
        segend_s = self._sval_out[segnames[-1]]
        if segnames[-1] not in self.beam_data:
            self.store_beam_data(
                segnames[-1], bm, segend_s + sstart_lattice, endelem.physical.end.z
            )
        return bm

    def reference_index(self, numbers: np.ndarray, ref_idx: int) -> int:
        """
        Get the index of the reference particle in the (possibly reduced)
        array of surviving particles, identified by their MAD-X `number`.
        """
        if ref_idx is None:
            return None
        target = int(ref_idx) + 1  # MAD-X numbers particles from 1
        idx = np.where(np.array(numbers).astype(int) == target)[0]
        if len(idx) == 0:
            return None
        return int(idx[0])

    def track_segment_single_particle(
        self,
        madx: Any,
        current_beam: rbf.beam,
        p0c: float,
        seg_len: float,
        segnames: List,
        seg_s0: float,
        sstart_lattice: float,
    ) -> rbf.beam:
        """
        Standard (single-particle) MAD-X tracking for one segment: the beam
        centroid is tracked, together with 12 probe trajectories used to
        build the linear map of the segment by finite differences. The full
        distribution is then transformed with the resulting map (centroid +
        R matrix); see :func:`~run`.

        The probes are observed at every diagnostic (`Screen`, `Marker`,
        `BPM`) within the segment as well as at its end, so that the map --
        and hence the transformed beam statistics -- are recorded along the
        whole line (via :func:`~store_beam_data`), not just at the segment
        boundaries (the accelerating cavities). Consistent with the
        ``single_particle`` contract, only the beam *statistics* are stored at
        the intermediate points; the beam distribution file is written once,
        for the end of the line (see :func:`~run_segments`).

        Returns
        -------
        :class:`~simba.Modules.Beams.beam`
            The (transformed) beam at the end of the segment
        """
        keys = ["x", "px", "y", "py", "t", "pt"]
        coords = current_beam.beam_to_madx_coords(p0c)
        tbar0 = coords["tbar"]
        zin = np.array([coords[k] for k in keys])
        centroid = np.mean(zin, axis=1)
        delta = abs(self.fd_delta)
        # centroid + (+/- delta) probes in each of the 6 canonical coordinates
        probes = [centroid]
        for k in range(6):
            for sign in (1, -1):
                probe = centroid.copy()
                probe[k] += sign * delta
                probes.append(probe)
        probes = np.array(probes).T
        probecoords = {k: probes[i] for i, k in enumerate(keys)}
        charge_total = abs(np.sum(np.array(current_beam.charge.val)))
        ref_index = current_beam.reference_particle_index
        # observe the probes at every diagnostic in the segment (and, via the
        # automatic end-of-sequence dump, at the segment end)
        observe = self.observation_points(segnames)
        trackdata = self.run_track(madx, probecoords, observe)

        def transformed_beam_at(s_local: float, zpos: float):
            """Beam obtained by applying the segment map (start -> ``s_local``,
            built from the 13 probes) to the full input distribution, or
            ``None`` if any probe was lost before ``s_local``."""
            data = self.extract_observation(trackdata, s_local)
            if len(data["x"]) != 13:
                return None
            zout = np.array([data[k] for k in keys])
            centroid_out = zout[:, 0]
            rmatrix = np.zeros((6, 6))
            for k in range(6):
                rmatrix[:, k] = (zout[:, 1 + 2 * k] - zout[:, 2 + 2 * k]) / (2 * delta)
            # transform the full distribution: z_out = c_out + R (z_in - c_in)
            transformed = centroid_out[:, np.newaxis] + rmatrix @ (
                zin - centroid[:, np.newaxis]
            )
            newcoords = {k: transformed[i] for i, k in enumerate(keys)}
            return self.pin.madx_coords_to_beam(
                newcoords, p0c, tbar0, s_local, zpos, zpos, charge_total,
                ref_index=ref_index,
            )

        # record the beam statistics at each diagnostic within the segment (no
        # beam file is written here -- only the end-of-line beam is, in run)
        for name, s_local in observe:
            elem = self._elements_with_drifts[name]
            bm = transformed_beam_at(s_local, elem.physical.middle.z)
            if bm is None:
                warn(f"MADX single-particle: probe particles lost at {name}")
                continue
            self.store_beam_data(
                name, bm, seg_s0 + s_local + sstart_lattice, elem.physical.middle.z
            )

        endelem = self._elements_with_drifts[segnames[-1]]
        bm_end = transformed_beam_at(seg_len, endelem.physical.end.z)
        if bm_end is None:
            raise RuntimeError(
                "MADX single-particle tracking lost probe particles at the "
                "segment end"
            )
        return bm_end

    def sample_beam(self, bm: rbf.beam, interval: int) -> rbf.beam:
        """
        Downsample a beam by the given interval, conserving the total charge.
        """
        newbeam = deepcopy(bm)
        nb = newbeam._beam
        idx = slice(None, None, int(interval))
        for key in ["x", "y", "z", "t", "px", "py", "pz", "nmacro", "status",
                    "particle_mass", "particle_rest_energy",
                    "particle_rest_energy_eV", "particle_charge"]:
            if hasattr(nb, key) and getattr(nb, key) is not None:
                val = getattr(nb, key)
                try:
                    setattr(nb, key, UnitValue(np.array(val.val)[idx], units=val.units))
                except Exception:
                    pass
        nb.set_total_charge(np.sum(np.array(bm.charge.val)))
        refidx = bm.reference_particle_index
        if refidx is not None and int(refidx) % int(interval) == 0:
            newbeam.reference_particle_index = int(refidx) // int(interval)
        else:
            newbeam.reference_particle_index = None
        return newbeam

    # ------------------------------------------------------------------
    # Post-processing
    # ------------------------------------------------------------------
    def postProcess(self) -> None:
        """
        Assemble the collected beam statistics and MAD-X model Twiss
        parameters into a Twiss summary file
        (``<lattice>_twiss.madx.hdf5``, readable by
        :func:`simba.Modules.Twiss.load_directory`), and update the global
        beam distribution with the beam at the end of the line.
        """
        super().postProcess()
        if len(self.beam_data) == 0:
            warn("MADX: no tracking data to post-process")
            return
        m0 = self.particle_rest_energy_eV
        rows = sorted(self.beam_data.items(), key=lambda kv: kv[1]["s"])
        twsdat = {
            "element_name": np.array([name for name, _ in rows], dtype="S"),
            "lattice_name": np.array([self.objectname for _ in rows], dtype="S"),
        }
        for key in [
            "s", "z", "t", "cp", "sigma_x", "sigma_y", "sigma_xp", "sigma_yp",
            "sigma_t", "sigma_z", "sigma_cp", "mean_x", "mean_y", "enx", "eny",
            "ex", "ey", "ecnx", "ecny", "beta_x_beam", "alpha_x_beam",
            "beta_y_beam", "alpha_y_beam", "eta_x_beam", "eta_xp_beam",
            "eta_y_beam", "eta_yp_beam",
        ]:
            twsdat[key] = np.array([d[key] for _, d in rows])
        cp = twsdat["cp"]
        E = np.sqrt(cp**2 + m0**2)
        twsdat["kinetic_energy"] = E - m0
        twsdat["gamma"] = E / m0
        twsdat["p"] = cp * elementary_charge / speed_of_light
        twsdat["mean_cp"] = cp
        twsdat["sigma_p"] = twsdat["sigma_cp"] / cp
        twsdat["enz"] = np.zeros(len(rows))
        twsdat["ez"] = np.zeros(len(rows))
        twsdat["beta_z"] = np.zeros(len(rows))
        twsdat["alpha_z"] = np.zeros(len(rows))
        twsdat["gamma_z"] = np.zeros(len(rows))
        # model twiss values (fall back to the beam values if the model
        # twiss is not available at an element)
        model_keys = {
            "beta_x": ("betx", "beta_x_beam"),
            "alpha_x": ("alfx", "alpha_x_beam"),
            "beta_y": ("bety", "beta_y_beam"),
            "alpha_y": ("alfy", "alpha_y_beam"),
            "eta_x": ("dx", "eta_x_beam"),
            "eta_xp": ("dpx", "eta_xp_beam"),
            "eta_y": ("dy", "eta_y_beam"),
            "eta_yp": ("dpy", "eta_yp_beam"),
            "mux": ("mux", None),
            "muy": ("muy", None),
        }
        scale = np.array(
            [
                d["cp"] / self.segment_p0c[name]
                if self.segment_p0c.get(name, 0) > 0
                else 1.0
                for name, d in rows
            ]
        )
        canonical_scaling = {"beta_x", "beta_y", "eta_x", "eta_y"}
        for key, (mkey, fallback) in model_keys.items():
            vals = []
            for i, (name, d) in enumerate(rows):
                mname = sanitize_string(name).lower()
                if mname in self.model_twiss:
                    val = self.model_twiss[mname][mkey]
                    if key in canonical_scaling:
                        val = val * scale[i]
                    vals.append(val)
                elif fallback is not None:
                    vals.append(d[fallback])
                else:
                    vals.append(0.0)
            twsdat[key] = np.array(vals)
        twsdat["gamma_x"] = (1 + twsdat["alpha_x"] ** 2) / twsdat["beta_x"]
        twsdat["gamma_y"] = (1 + twsdat["alpha_y"] ** 2) / twsdat["beta_y"]
        self.tws = twsdat
        save_madx_twiss_hdf(
            self,
            filename=(
                f'{self.global_parameters["master_subdir"]}/'
                f"{self.objectname}_twiss.madx.hdf5"
            ),
            twiss=twsdat,
        )
        # update the global beam object with the distribution at the end of
        # the line, so that subsequent lattices start from it
        endfile = os.path.join(
            self.global_parameters["master_subdir"], f"{self.end}.openpmd.hdf5"
        )
        if os.path.isfile(endfile):
            rbf.openpmd.read_openpmd_beam_file(
                self.global_parameters["beam"], endfile
            )
